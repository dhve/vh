import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pages, routes } from '../routes.mjs';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
let count = 0;
for (const route of routes.filter(route => route.path)) {
  const template = await readFile(new URL(pages[route.page].source, root), 'utf8');
  const base = '../'.repeat(route.path.split('/').filter(Boolean).length);
  const html = template
    .replace('<head>', `<head>\n  <!-- Generated by scripts/build-routes.mjs; edit ${pages[route.page].source} instead. -->\n  <base href="${base}">`)
    .replace('class="skip-link" href="#main"', `class="skip-link" href="${route.path}#main"`);
  const directory = new URL(route.path, root);
  const output = new URL('index.html', directory);
  if (check) {
    const existing = await readFile(output, 'utf8').catch(() => null);
    if (existing !== html) throw new Error(`Run npm run build to update ${route.path}index.html`);
  } else {
    await mkdir(directory, { recursive: true });
    await writeFile(output, html);
  }
  count++;
}
console.log(`${check ? 'Verified' : 'Generated'} ${count} clean URL entries.`);
